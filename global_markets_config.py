def render_hreflang_tags() -> str:
    lines = []
    for cid, loc in MARKET_LOCALES.items():
        href = f"{SITE_URL}{loc['path']}"
        lines.append(f'    <link rel="alternate" hreflang="{loc["hreflang"]}" href="{href}" />')
    lines.append(f'    <link rel="alternate" hreflang="x-default" href="{SITE_URL}/en/" />')
    return "\n".join(lines)


